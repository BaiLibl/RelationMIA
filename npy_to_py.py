"""Export a trusted NumPy object cache as an importable Python data file."""

import argparse
from pathlib import Path
from pprint import pformat

import numpy as np


def to_python(value):
    if isinstance(value, np.ndarray):
        return to_python(value.tolist())
    if isinstance(value, np.generic):
        return to_python(value.item())
    if isinstance(value, dict):
        return {to_python(key): to_python(item) for key, item in value.items()}
    if isinstance(value, list):
        return [to_python(item) for item in value]
    if isinstance(value, tuple):
        return tuple(to_python(item) for item in value)
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    output = args.output or args.input.with_suffix(".py")
    if output.resolve() == args.input.resolve():
        parser.error("Input and output must be different files")

    # Object caches use pickle: load only files from a trusted source.
    records = to_python(np.load(args.input, allow_pickle=True))
    source = (
        "# Generated by npy_to_py.py; all records are stored in data.\n"
        "nan = float('nan')\ninf = float('inf')\n\n"
        f"data = {pformat(records, width=100, sort_dicts=False)}\n"
    )
    compile(source, str(output), "exec")
    output.parent.mkdir(parents=True, exist_ok=True)
    # Avoid overwriting an existing Python source file accidentally.
    with output.open("x", encoding="utf-8") as handle:
        handle.write(source)
    count = len(records) if isinstance(records, (list, tuple)) else 1
    print(f"Saved {count} records to {output}")


if __name__ == "__main__":
    main()
